import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
const quote = (value: string) => "'" + value.replaceAll("'", "''") + "'";
const names = (await readdir('supabase/migrations')).filter((n) => n.endsWith('.sql')).sort();
const migrations = await Promise.all(
  names.map(async (name) => {
    const sql = (await readFile(`supabase/migrations/${name}`, 'utf8')).replace(/\r\n/g, '\n');
    return { name, sql, hash: createHash('sha256').update(sql).digest('hex') };
  }),
);
const expected = migrations.map((m) => `(${quote(m.name)}, ${quote(m.hash)})`).join(',\n');
const script = `-- GENERATED by npm run db:bootstrap:generate; never edit migration contents here.
-- Run the ENTIRE script in the NEW OneBoss project's Supabase SQL Editor as postgres.
-- Contains no credentials. Never paste passwords or API keys into this script.
-- Atomic: errors roll back every change. Matching completed migrations are a safe no-op.
BEGIN;
SELECT pg_advisory_xact_lock(601106);
DO $oneboss_bootstrap$
BEGIN
  IF to_regclass('public.oneboss_migrations') IS NOT NULL THEN
    IF (SELECT count(*) FROM public.oneboss_migrations) = ${migrations.length}
      AND (SELECT count(*) FROM public.oneboss_migrations WHERE (name,hash) IN (${expected})) = ${migrations.length}
      AND to_regclass('public.organizations') IS NOT NULL
      AND to_regclass('public.deliveries') IS NOT NULL THEN
      RAISE NOTICE 'OneBoss migrations already applied; existing data retained';
      RETURN;
    END IF;
    RAISE EXCEPTION 'Existing migration history differs. Stop and use the versioned migration runner.';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
      WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m','f')) THEN
    RAISE EXCEPTION 'This bootstrap requires an empty public schema. Existing tables/views were preserved.';
  END IF;
${migrations.map((m) => `\n-- Migration: ${m.name}; sha256: ${m.hash}\n${m.sql}`).join('\n')}
  CREATE TABLE public.oneboss_migrations (
    name text PRIMARY KEY, hash text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now()
  );
  ALTER TABLE public.oneboss_migrations ENABLE ROW LEVEL SECURITY;
  REVOKE ALL ON public.oneboss_migrations FROM anon, authenticated;
  INSERT INTO public.oneboss_migrations(name,hash) VALUES ${expected};
END
$oneboss_bootstrap$;
NOTIFY pgrst, 'reload schema';
COMMIT;
SELECT 'OneBoss database initialized; application connection still requires separate validation' AS result;
`;
await writeFile('docs/setup-supabase.sql', script);
console.log(
  `Generated SQL Editor bootstrap from ${migrations.length} migrations; no secrets read.`,
);
